function fileLesson(item, index) {
  const fileName = item.path.split('/').pop();
  const calledBy = item.calledBy.length ? item.calledBy.join(', ') : 'Không có file nào import trực tiếp; công cụ hoặc người lập trình sử dụng file này.';
  const uses = item.uses.length ? item.uses.join(', ') : 'Không phụ thuộc source file khác.';

  return {
    id: 'file-' + item.id,
    section: item.group,
    filePath: item.path,
    shortTitle: fileName,
    eyebrow: 'File ' + String(index + 1).padStart(2, '0') + ' · ' + groupLabels[item.group],
    title: fileName + ' làm gì trong dự án?',
    summary: item.summary,
    objectives: [
      'Nói được trách nhiệm chính của ' + item.path + '.',
      'Biết file nào gọi nó và nó phụ thuộc vào đâu.',
      'Tự dựng lại phần khung quan trọng mà không chép nguyên dự án.'
    ],
    files: [item.path],
    concepts: [
      { title: 'Chạy ở đâu?', text: item.runtime },
      { title: 'Ai dùng file này?', text: calledBy },
      { title: 'File này dùng gì?', text: uses },
      { title: 'Đọc theo thứ tự', text: item.read.join(' → ') },
      { title: 'Điểm cần hiểu', text: item.key },
      { title: 'Lưu ý khi viết lại', text: item.warning }
    ],
    diagram: item.flow.join('\n  ↓\n'),
    code: {
      label: 'Khung cần nhớ khi tự viết lại',
      content: item.rewrite.join('\n')
    },
    exercise: {
      title: 'Tự học file ' + fileName,
      steps: [
        'Mở ' + item.path + ' và tìm đúng các phần: ' + item.read.join(', ') + '.',
        'Đóng phần giải thích, tự nói lại nhiệm vụ của file bằng 2–3 câu.',
        item.practice,
        'Chạy lint hoặc chức năng liên quan để kiểm tra phần vừa viết.'
      ]
    },
    quiz: {
      question: 'Nếu bỏ file ' + fileName + ', phần nào của hệ thống sẽ bị ảnh hưởng?',
      answer: item.impact
    }
  };
}

